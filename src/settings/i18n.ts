export function translate(language: AppLanguage, chinese: string): string {
  return language === "en" ? english[chinese] ?? chinese : chinese;
}

export function plural(language: AppLanguage, count: number, chineseUnit: string, englishUnit: string): string {
  if (language === "zh-CN") return `${count} 个${chineseUnit}`;
  return `${count} ${englishUnit}${count === 1 ? "" : "s"}`;
}
